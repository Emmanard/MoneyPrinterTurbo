"""Synthesised sound effects for transitions and text cards.

Every sound is generated by ffmpeg from its own sources (noise and sine expressions); there
are no sample files and no downloads. Off unless a transition or a card asks for one.

Pure functions: validation, placing events on the final timeline, and the ffmpeg graph that
renders them all into one audio track as long as the video.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

SFX_TYPES = ("whoosh", "click", "riser")
SFX_KEYS = ("type", "volume", "offset")
SETTINGS_KEYS = ("enabled", "volume")
DEFAULT_VOLUME = 0.35
MAX_OFFSET = 1.0
MAX_EVENTS = 100
SAMPLE_RATE = 48000
SOUND_VERSION = "sfx-v1"
# Seconds each sound lasts.
SOUND_SECONDS = {"whoosh": 0.5, "click": 0.06, "riser": 1.2}
_NOISE_SEED = 7  # fixed, so the whoosh is the same every time


def _is_number(value: object) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def parse_sfx(raw: object, label: str, errors: list[str]) -> dict | None:
    """Validate {type, volume, offset}. ``volume`` may be left out (the project default
    applies); ``offset`` is seconds from the event (a transition's start, a card's start)."""
    if raw is None:
        return None
    if not isinstance(raw, dict):
        errors.append(f"{label}: must be an object like {{\"type\": \"whoosh\", \"volume\": 0.35}}")
        return None
    for key in raw:
        if key not in SFX_KEYS:
            errors.append(f"{label}: unknown field: {key}")
    kind = raw.get("type")
    ok = True
    if kind not in SFX_TYPES:
        errors.append(f"{label}.type: must be one of {', '.join(SFX_TYPES)}")
        ok = False
    spec: dict = {"type": kind}
    if "volume" in raw:
        volume = raw["volume"]
        if not _is_number(volume) or not 0 <= volume <= 1:
            errors.append(f"{label}.volume: must be a number from 0 to 1")
            ok = False
        else:
            spec["volume"] = float(volume)
    offset = raw.get("offset", 0)
    if not _is_number(offset) or not -MAX_OFFSET <= offset <= MAX_OFFSET:
        errors.append(f"{label}.offset: must be a number of seconds from -{MAX_OFFSET:g} to {MAX_OFFSET:g}")
        ok = False
    else:
        spec["offset"] = float(offset)
    return spec if ok else None


def parse_settings(raw: object, label: str, errors: list[str]) -> dict | None:
    """Validate settings.sfx {enabled, volume}."""
    if raw is None:
        return None
    if not isinstance(raw, dict):
        errors.append(f"{label}: must be an object like {{\"enabled\": true, \"volume\": 0.35}}")
        return None
    spec: dict = {}
    for key, value in raw.items():
        if key not in SETTINGS_KEYS:
            errors.append(f"{label}: unknown field: {key}")
        elif key == "enabled":
            if not isinstance(value, bool):
                errors.append(f"{label}.enabled: must be true or false")
            else:
                spec[key] = value
        elif key == "volume":
            if not _is_number(value) or not 0 <= value <= 1:
                errors.append(f"{label}.volume: must be a number from 0 to 1")
            else:
                spec[key] = float(value)
    return spec


@dataclass(frozen=True)
class Event:
    kind: str
    time: float    # seconds on the final timeline
    volume: float  # linear, 0 to 1

    def key(self) -> list:
        return [self.kind, round(self.time * 1000), round(self.volume, 4)]


def events_for(scenes, frames: list[int], tails: list[int], fps: int, settings: dict | None):
    """Place every requested sound on the final timeline.

    Returns (events, errors). A transition's sound is at the start of the transition plus its
    offset; a card's sound is at the card's start inside its scene plus its offset. Scene i
    starts at the sum of (frames - tail) of the scenes before it, because each transition
    overlaps the next scene. The master switch ``settings.sfx.enabled`` false drops them all."""
    settings = settings or {}
    if settings.get("enabled", True) is False:
        return [], []
    default = settings.get("volume", DEFAULT_VOLUME)
    total = (sum(frames) - sum(tails)) / fps
    events: list[Event] = []
    errors: list[str] = []
    starts = []
    cursor = 0
    for index in range(len(frames)):
        starts.append(cursor / fps)
        cursor += frames[index] - tails[index]
    for index, scene in enumerate(scenes):
        transition = scene.transition
        sfx = getattr(transition, "sfx", None) if transition is not None else None
        if sfx is not None and index + 1 < len(frames):
            events.append(_place(sfx, starts[index + 1], default, f"scene {scene.id}.transition.sfx",
                                 total, errors))
        for number, card in enumerate(scene.text_cards, start=1):
            if card.sfx is not None:
                events.append(_place(card.sfx, starts[index] + card.start, default,
                                     f"scene {scene.id}.text_cards[{number - 1}].sfx", total, errors))
    if len(events) > MAX_EVENTS:
        errors.append(f"sfx: {len(events)} sound effects; the limit is {MAX_EVENTS}")
    return sorted(events, key=lambda event: (event.time, event.kind)), errors


def _place(spec: dict, base: float, default: float, label: str, total: float, errors: list[str]) -> Event:
    time = base + spec.get("offset", 0.0)
    if time < 0 or time > total + 1e-6:
        errors.append(f"{label}: lands at {time:.2f}s, outside the video (0 to {total:.2f}s); "
                      "change the offset")
    return Event(spec["type"], max(0.0, min(time, total)), spec.get("volume", default))


def _source(kind: str) -> str:
    fmt = f"aformat=sample_fmts=fltp:sample_rates={SAMPLE_RATE}:channel_layouts=stereo"
    seconds = SOUND_SECONDS[kind]
    if kind == "whoosh":
        body = (f"anoisesrc=d={seconds}:c=pink:r={SAMPLE_RATE}:a=0.8:seed={_NOISE_SEED},"
                "highpass=f=250,lowpass=f=5000,"
                "afade=t=in:st=0:d=0.22:curve=qsin,afade=t=out:st=0.22:d=0.28:curve=qsin")
    elif kind == "click":
        body = f"aevalsrc='0.9*sin(2*PI*1800*t)*exp(-t*90)':d={seconds}:s={SAMPLE_RATE}"
    else:
        body = (f"aevalsrc='0.7*sin(2*PI*(300*t+400*t*t))*pow(t/{seconds},2)':d={seconds}:"
                f"s={SAMPLE_RATE}")
    return f"{body},{fmt}"


def sound_graph(kind: str) -> str:
    """The filter chain that synthesises one sound, e.g. for an audition render."""
    return _source(kind)


def build_graph(events: list[Event], total_seconds: float) -> str:
    """One filter graph: silence as long as the video plus every event, each delayed to its
    time and padded to the full length so amix keeps a constant weight, then summed.
    The output label is [a]."""
    count = len(events) + 1
    parts = [f"anullsrc=r={SAMPLE_RATE}:cl=stereo:d={total_seconds:.6f}[base]"]
    labels = ["[base]"]
    for index, event in enumerate(events):
        delay = round(event.time * 1000)
        parts.append(
            f"{_source(event.kind)},volume={event.volume:.4f},adelay={delay}|{delay},"
            f"apad=whole_dur={total_seconds:.6f},atrim=end={total_seconds:.6f}[e{index}]"
        )
        labels.append(f"[e{index}]")
    parts.append(
        f"{''.join(labels)}amix=inputs={count}:duration=longest:dropout_transition=0,"
        f"volume={count},alimiter=limit=0.95:level=0[a]"
    )
    return ";".join(parts)


def sfx_key(events: list[Event], total_seconds: float) -> list:
    return [SOUND_VERSION, round(total_seconds, 6), [event.key() for event in events]]
